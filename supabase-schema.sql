-- Run this in Supabase: SQL Editor > New query > Run.
create table if not exists public.date_selections (
  id bigint generated by default as identity primary key,
  selected_date date not null,
  created_at timestamptz not null default now()
);

alter table public.date_selections enable row level security;

create policy "Anyone can submit a date"
on public.date_selections for insert
to anon
with check (selected_date >= current_date);

create policy "Anyone can read recent dates"
on public.date_selections for select
to anon
using (true);

grant usage on schema public to anon;
grant select, insert on public.date_selections to anon;
grant usage, select on sequence public.date_selections_id_seq to anon;
